import "dotenv/config";
import test, { mock } from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs/promises";
import pg from "pg";
import nodemailer from "nodemailer";
import pool from "../config/database.js";

test("all account roles: verification, cooldown, expiry, attempts, email changes and SMTP failures", async () => {
  const schema = `email_test_${crypto.randomBytes(8).toString("hex")}`;
  const admin = new pg.Client({
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT),
    database: process.env.DB_NAME,
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
  });
  const mailbox = [];
  let smtpFail = false,
    server,
    connected = false,
    number = 123456;
  const smtp = mock.method(nodemailer, "createTransport", () => ({
    sendMail: async (message) => {
      if (smtpFail) throw new Error("Test SMTP failure");
      mailbox.push(message);
      return { messageId: "test-only" };
    },
  }));
  const rng = mock.method(crypto, "randomInt", () => number++);
  try {
    await admin.connect();
    connected = true;
    await admin.query(`CREATE SCHEMA ${schema}`);
    pool.options.options = `-c search_path=${schema}`;
    for (const table of [
      "users",
      "restaurants",
      "delivery_agents",
      "admins",
      "site_settings",
    ]) {
      await pool.query(
        `CREATE TABLE ${table} (LIKE public.${table} INCLUDING ALL)`
      );
      if (table !== "site_settings")
        await pool.query(
          `ALTER TABLE ${table} ALTER COLUMN id DROP DEFAULT;ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`
        );
    }
    await pool.query(
      await fs.readFile(
        new URL(
          "../database/migrations/018_email_verification.sql",
          import.meta.url
        ),
        "utf8"
      )
    );
    await pool.query(
      "INSERT INTO users(name,email,password) VALUES('Test user','user@example.test','not-used')"
    );
    await pool.query(
      "INSERT INTO restaurants(owner_name,restaurant_name,email,phone,password,address_line,city,state,pincode) VALUES('Owner','Test','restaurant@example.test','9000000001','not-used','Test street','Kanpur','UP','208002')"
    );
    await pool.query(
      "INSERT INTO delivery_agents(public_id,name,email,phone,password) VALUES('email-test-rider','Rider','delivery@example.test','9000000002','not-used')"
    );
    await pool.query(
      "INSERT INTO admins(name,email,password) VALUES('Admin','admin@example.test','not-used')"
    );
    const { default: app } = await import("../app.js");
    const jwt = (await import("jsonwebtoken")).default;
    server = app.listen(0, "127.0.0.1");
    await new Promise((resolve) => server.once("listening", resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    const definitions = {
      user: ["user", "users", { role: "user", userId: 1 }],
      restaurant: [
        "restaurant",
        "restaurants",
        { role: "restaurant", restaurantId: 1 },
      ],
      delivery: [
        "delivery",
        "delivery_agents",
        {
          role: "deliveryAgent",
          deliveryAgentId: 1,
          publicId: "email-test-rider",
        },
      ],
      admin: ["admin", "admins", { role: "SUPER_ADMIN", adminId: 1 }],
    };
    const request = async (kind, endpoint = "", body, tokenOverride) => {
      const token =
        tokenOverride ?? jwt.sign(definitions[kind][2], process.env.JWT_SECRET);
      const response = await fetch(
        `${base}/api/${definitions[kind][0]}/email-verification${endpoint}`,
        {
          method: body ? "POST" : "GET",
          headers: {
            Authorization: `Bearer ${token}`,
            ...(body ? { "Content-Type": "application/json" } : {}),
          },
          body: body ? JSON.stringify(body) : undefined,
        }
      );
      return {
        status: response.status,
        headers: response.headers,
        body: await response.json(),
      };
    };
    for (const [kind, [, table]] of Object.entries(definitions)) {
      assert.equal((await request(kind)).body.data.emailVerified, false);
      const sent = await request(kind, "/send", {
        email: "attacker@example.test",
      });
      assert.equal(sent.status, 200);
      assert.equal(sent.body.data.email, `${kind}@example.test`);
      const mail = mailbox.at(-1);
      assert.equal(mail.to, `${kind}@example.test`);
      const code = mail.text.match(/code is (\d{6})/)[1];
      assert.ok(mail.html.includes("Your verification code"));
      assert.ok(mail.html.includes(code));
      assert.ok(!JSON.stringify(sent.body).includes(code));
      const stored = (
        await pool.query(
          "SELECT * FROM email_verifications WHERE account_kind=$1",
          [kind]
        )
      ).rows[0];
      assert.match(stored.code_hash, /^[a-f0-9]{64}$/);
      assert.notEqual(stored.code_hash, code);
      const cooldown = await request(kind, "/send", {});
      assert.equal(cooldown.status, 429);
      assert.ok(Number(cooldown.headers.get("retry-after")) > 0);
      assert.equal((await request(kind)).body.data.codePending, true);
      assert.equal(
        (await request(kind, "/verify", { code: "000000" })).status,
        400
      );
      assert.equal(
        (await request(kind, "/verify", { code })).body.data.emailVerified,
        true
      );
      assert.equal(
        (await pool.query(`SELECT email_verified FROM ${table} WHERE id=1`))
          .rows[0].email_verified,
        true
      );
      const count = mailbox.length;
      assert.equal(
        (await request(kind, "/send", {})).body.data.emailVerified,
        true
      );
      assert.equal(mailbox.length, count);
      assert.equal(
        (
          await pool.query(
            "SELECT COUNT(*) FROM email_verifications WHERE account_kind=$1",
            [kind]
          )
        ).rows[0].count,
        "0"
      );
      await pool.query(`UPDATE ${table} SET email=$1 WHERE id=1`, [
        `${kind}.changed@example.test`,
      ]);
      assert.equal((await request(kind)).body.data.emailVerified, false);
    }
    const userToken = jwt.sign(definitions.user[2], process.env.JWT_SECRET);
    assert.equal(
      (await request("restaurant", "/send", {}, userToken)).status,
      403
    );
    assert.equal((await request("user", "", "", "invalid-token")).status, 401);
    await request("user", "/send", {});
    let code = mailbox.at(-1).text.match(/code is (\d{6})/)[1];
    for (let i = 0; i < 5; i++)
      assert.equal(
        (await request("user", "/verify", { code: "000000" })).status,
        400
      );
    assert.equal((await request("user", "/verify", { code })).status, 429);
    await pool.query(
      "UPDATE email_verifications SET sent_at=NOW()-INTERVAL '61 seconds' WHERE account_kind='user'"
    );
    await request("user", "/send", {});
    const fresh = mailbox.at(-1).text.match(/code is (\d{6})/)[1];
    assert.equal((await request("user", "/verify", { code })).status, 400);
    await pool.query(
      "UPDATE email_verifications SET sent_at=NOW()-INTERVAL '61 seconds' WHERE account_kind='user'"
    );
    smtpFail = true;
    assert.equal((await request("user", "/send", {})).status, 503);
    smtpFail = false;
    assert.equal(
      (await request("user", "/verify", { code: fresh })).body.data
        .emailVerified,
      true
    );
    await pool.query(
      "UPDATE users SET email='new-again@example.test' WHERE id=1"
    );
    await request("user", "/send", {});
    code = mailbox.at(-1).text.match(/code is (\d{6})/)[1];
    await pool.query(
      "UPDATE email_verifications SET expires_at=NOW()-INTERVAL '1 second' WHERE account_kind='user'"
    );
    assert.equal((await request("user", "/verify", { code })).status, 410);
    await pool.query(
      "UPDATE email_verifications SET sent_at=NOW()-INTERVAL '61 seconds',send_count=5 WHERE account_kind='user'"
    );
    assert.equal((await request("user", "/send", {})).status, 429);
    await pool.query("UPDATE users SET is_blocked=TRUE WHERE id=1");
    assert.equal((await request("user", "/send", {})).status, 403);
  } finally {
    if (server) await new Promise((resolve) => server.close(resolve));
    smtp.mock.restore();
    rng.mock.restore();
    await pool.end();
    if (connected) {
      await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      await admin.end();
    }
  }
});
