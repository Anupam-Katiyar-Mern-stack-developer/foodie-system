import "dotenv/config";
import test, { mock } from "node:test";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import pg from "pg";
import nodemailer from "nodemailer";
import { createRequire } from "node:module";
import pool from "../config/database.js";
import { deleteImage } from "../utils/storage/imageStorage.js";

test("partner registration, logo upload and delivery assignment use an isolated database schema", async () => {
  const schema = `partner_test_${crypto.randomBytes(8).toString("hex")}`;
  const admin = new pg.Client({
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT),
    database: process.env.DB_NAME,
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
  });
  let server;
  let io;
  const clients = [];
  let logo;
  let connected = false;
  const smtp = mock.method(nodemailer, "createTransport", () => ({
    sendMail: async () => ({ messageId: "test-only" }),
  }));
  try {
    await admin.connect();
    connected = true;
    await admin.query(`CREATE SCHEMA ${schema}`);
    pool.options.options = `-c search_path=${schema}`;
    // Copy structure and defaults, then replace every serial default with a local identity.
    // No fixtures or sequence increments touch the live tables.
    for (const table of [
      "restaurants",
      "delivery_agents",
      "orders",
      "order_groups",
      "order_items",
      "delivery_assignments",
    ]) {
      await pool.query(
        `CREATE TABLE ${table} (LIKE public.${table} INCLUDING ALL)`
      );
      await pool.query(`ALTER TABLE ${table} ALTER COLUMN id DROP DEFAULT`);
      await pool.query(
        `ALTER TABLE ${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`
      );
    }
    const { default: app } = await import("../app.js");
    const jwt = (await import("jsonwebtoken")).default;
    const delivery = await import("../services/delivery.service.js");
    const restaurant = await import("../services/restaurant.service.js");
    server = app.listen(0, "127.0.0.1");
    await new Promise((resolve) => server.once("listening", resolve));
    const { initializeSocket } = await import("../socket/socket.js");
    io = initializeSocket(server);
    const connectClient = createRequire(
      new URL("../../Frontend/package.json", import.meta.url)
    )("socket.io-client").io;
    const waitEvent = (client, event) =>
      new Promise((resolve, reject) => {
        const timeout = setTimeout(() => {
          client.off(event, handler);
          reject(new Error(`Timed out: ${event}`));
        }, 5000);
        const handler = (data) => {
          clearTimeout(timeout);
          resolve(data);
        };
        client.once(event, handler);
      });
    const connect = async (token) => {
      const client = connectClient(
        `http://127.0.0.1:${server.address().port}`,
        {
          auth: { token },
          transports: ["websocket"],
          reconnection: false,
          autoConnect: false,
        }
      );
      clients.push(client);
      const ready = waitEvent(client, "connect");
      client.connect();
      await ready;
      return client;
    };
    const base = `http://127.0.0.1:${server.address().port}`;
    const request = async (path, body, token, method = "POST") => {
      const form = body instanceof FormData;
      const response = await fetch(base + path, {
        method,
        headers: {
          ...(!form && body ? { "Content-Type": "application/json" } : {}),
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        body: body ? (form ? body : JSON.stringify(body)) : undefined,
      });
      return { status: response.status, body: await response.json() };
    };
    const registration = {
      ownerName: "Test owner",
      restaurantName: "Test kitchen",
      email: "kitchen@example.test",
      phone: "9000000001",
      password: "TestPassword123",
      addressLine: "Test street 12",
      city: "Kanpur",
      state: "UP",
      pincode: "208027",
      latitude: 26.47,
      longitude: 80.35,
    };
    const created = await request("/api/restaurant/register", registration);
    assert.equal(created.status, 201, JSON.stringify(created.body));
    assert.equal(created.body.data.approvalStatus, "PENDING");
    assert.equal(
      (await request("/api/restaurant/register", registration)).status,
      409
    );
    assert.equal(
      (
        await request("/api/restaurant/register", {
          ...registration,
          email: "other@example.test",
          phone: "9000000002",
          addressLine: "",
        })
      ).status,
      400
    );
    const restaurantId = created.body.data.id;
    await pool.query(
      "UPDATE restaurants SET approval_status='APPROVED',is_open=TRUE WHERE id=$1",
      [restaurantId]
    );
    assert.equal(
      (
        await request("/api/restaurant/login", {
          email: registration.email,
          password: registration.password,
        })
      ).status,
      200
    );
    const token = jwt.sign(
      { restaurantId, role: "restaurant" },
      process.env.JWT_SECRET
    );
    const png = Buffer.from(
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a9WQAAAAASUVORK5CYII=",
      "base64"
    );
    const form = new FormData();
    form.append("logo", new Blob([png], { type: "image/png" }), "logo.png");
    const uploaded = await request(
      "/api/restaurant/profile",
      form,
      token,
      "PATCH"
    );
    assert.equal(uploaded.status, 200, JSON.stringify(uploaded.body));
    logo = uploaded.body.data.logo;
    assert.match(logo, /^\/images\/logo\//);
    assert.equal((await fetch(base + logo)).status, 200);
    const preserved = await request(
      "/api/restaurant/profile",
      { description: "Updated description" },
      token,
      "PATCH"
    );
    assert.equal(preserved.body.data.logo, logo);
    const publicList = await restaurant.getRestaurantsService({});
    assert.equal(publicList.pagination.total, 1);
    assert.equal(publicList.restaurants[0].logo, logo);
    assert.equal(
      (
        await restaurant.getPublicRestaurantBySlugService({
          restaurantSlug: created.body.data.slug,
        })
      ).logo,
      logo
    );

    const bicycle = {
      name: "Cycle rider",
      email: "cycle@example.test",
      phone: "9000000010",
      password: "TestPassword123",
      vehicleType: "BICYCLE",
      vehicleNumber: null,
      address: "Test rider address",
    };
    const rider = await request("/api/delivery/register", bicycle);
    assert.equal(rider.status, 201, JSON.stringify(rider.body));
    assert.equal(rider.body.data.vehicleNumber, null);
    assert.equal(rider.body.data.approvalStatus, "PENDING");
    assert.equal(
      (await request("/api/delivery/register", bicycle)).status,
      409
    );
    assert.equal(
      (
        await request("/api/delivery/register", {
          ...bicycle,
          email: "short@example.test",
          phone: "9000000011",
          password: "123456",
        })
      ).status,
      400
    );
    assert.equal(
      (
        await request("/api/delivery/register", {
          ...bicycle,
          email: "bike@example.test",
          phone: "9000000012",
          vehicleType: "BIKE",
        })
      ).status,
      400
    );
    const bike = await request("/api/delivery/register", {
      ...bicycle,
      email: "bike@example.test",
      phone: "9000000012",
      vehicleType: "BIKE",
      vehicleNumber: "up78 ab1234",
    });
    assert.equal(bike.status, 201, JSON.stringify(bike.body));
    assert.equal(bike.body.data.vehicleNumber, "UP78 AB1234");
    const riderId = (
      await pool.query("SELECT id FROM delivery_agents WHERE public_id=$1", [
        rider.body.data.publicId,
      ])
    ).rows[0].id;
    assert.equal(
      (
        await request("/api/delivery/login", {
          email: bicycle.email,
          password: bicycle.password,
        })
      ).status,
      403
    );
    await pool.query(
      "UPDATE delivery_agents SET approval_status='APPROVED' WHERE id=$1",
      [riderId]
    );
    assert.equal(
      (
        await request("/api/delivery/login", {
          email: bicycle.email,
          password: bicycle.password,
        })
      ).status,
      200
    );
    await delivery.updateDeliveryStatusService({
      deliveryAgentId: riderId,
      isOnline: true,
    });
    await delivery.updateDeliveryLocationService({
      deliveryAgentId: riderId,
      latitude: 26.471,
      longitude: 80.351,
    });
    await assert.rejects(
      () =>
        delivery.updateDeliveryLocationService({
          deliveryAgentId: riderId,
          latitude: null,
          longitude: null,
        }),
      /Valid latitude/
    );
    const group = (
      await pool.query(
        `INSERT INTO order_groups(checkout_number,user_id,delivery_name,delivery_phone,address_line,city,state,pincode,payment_method,payment_status,grand_total) VALUES('TEST-CHECKOUT',1,'Test buyer','9000000099','Test street','Kanpur','UP','208027','COD','PENDING',120) RETURNING id`
      )
    ).rows[0];
    const order = (
      await pool.query(
        `INSERT INTO orders(order_number,order_group_id,restaurant_id,status,subtotal,delivery_fee,tax_amount,total_amount) VALUES('TEST-ORDER',$1,$2,'READY_FOR_PICKUP',100,20,0,120) RETURNING id`,
        [group.id, restaurantId]
      )
    ).rows[0];
    const query = { restaurantId, orderNumber: "TEST-ORDER" };
    const available = await delivery.getAvailableDeliveryAgentsForOrderService(
      query
    );
    assert.equal(available.agents.length, 1);
    assert.equal(available.agents[0].publicId, rider.body.data.publicId);
    const httpList = await request(
      "/api/restaurant/orders/TEST-ORDER/delivery-agents",
      undefined,
      token,
      "GET"
    );
    assert.equal(httpList.status, 200);
    assert.equal(httpList.body.data.agents.length, 1);
    await pool.query(
      "UPDATE delivery_agents SET location_updated_at=NOW()-INTERVAL '31 minutes' WHERE id=$1",
      [riderId]
    );
    assert.equal(
      (await delivery.getAvailableDeliveryAgentsForOrderService(query)).agents
        .length,
      0
    );
    await delivery.updateDeliveryLocationService({
      deliveryAgentId: riderId,
      latitude: 26.471,
      longitude: 80.351,
    });
    await pool.query(
      "UPDATE restaurants SET latitude=NULL,longitude=NULL WHERE id=$1",
      [restaurantId]
    );
    await assert.rejects(
      () => delivery.getAvailableDeliveryAgentsForOrderService(query),
      /Restaurant location/
    );
    await pool.query(
      "UPDATE restaurants SET latitude=26.47,longitude=80.35 WHERE id=$1",
      [restaurantId]
    );
    const riderToken = jwt.sign(
      {
        deliveryAgentId: riderId,
        publicId: rider.body.data.publicId,
        role: "deliveryAgent",
      },
      process.env.JWT_SECRET
    );
    const restaurantSocket = await connect(token);
    const riderSocket = await connect(riderToken);
    const offerEvent = waitEvent(riderSocket, "delivery:new-offer");
    const offered = await request(
      "/api/restaurant/orders/TEST-ORDER/delivery-offer",
      { deliveryAgentPublicId: rider.body.data.publicId },
      token
    );
    assert.equal(offered.status, 201, JSON.stringify(offered.body));
    assert.equal((await offerEvent).orderNumber, "TEST-ORDER");
    assert.equal(
      (
        await delivery.getDeliveryOrderOfferService({
          deliveryAgentId: riderId,
        })
      ).orderNumber,
      "TEST-ORDER"
    );
    const restaurantEvent = waitEvent(
      restaurantSocket,
      "restaurant:delivery-offer-response"
    );
    const accepted = await request(
      "/api/delivery/orders/TEST-ORDER/accept",
      undefined,
      riderToken,
      "PATCH"
    );
    assert.equal(accepted.status, 200, JSON.stringify(accepted.body));
    assert.equal(accepted.body.data.status, "DELIVERY_ASSIGNED");
    assert.equal((await restaurantEvent).status, "ACCEPTED");
    const joined = await new Promise((resolve) =>
      restaurantSocket.emit(
        "order:join",
        { orderNumber: "TEST-ORDER" },
        resolve
      )
    );
    assert.equal(joined.success, true);
    const locationEvent = waitEvent(
      restaurantSocket,
      "delivery:location-updated"
    );
    assert.equal(
      (
        await request(
          "/api/delivery/location",
          { latitude: 26.472, longitude: 80.352 },
          riderToken,
          "PATCH"
        )
      ).status,
      200
    );
    assert.equal((await locationEvent).latitude, 26.472);
    assert.equal(
      (
        await pool.query(
          "SELECT is_available FROM delivery_agents WHERE id=$1",
          [riderId]
        )
      ).rows[0].is_available,
      false
    );
    await assert.rejects(
      () =>
        delivery.acceptDeliveryOrderService({
          deliveryAgentId: riderId,
          orderNumber: "TEST-ORDER",
        }),
      /unavailable/
    );
    assert.equal(
      (
        await pool.query(
          "SELECT assigned_delivery_agent_id FROM orders WHERE id=$1",
          [order.id]
        )
      ).rows[0].assigned_delivery_agent_id,
      riderId
    );
  } finally {
    clients.forEach((client) => client.disconnect());
    if (io) await new Promise((resolve) => io.close(resolve));
    else if (server) await new Promise((resolve) => server.close(resolve));
    if (logo) await deleteImage(logo);
    smtp.mock.restore();
    await pool.end();
    if (connected) {
      await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      await admin.end();
    }
  }
});
